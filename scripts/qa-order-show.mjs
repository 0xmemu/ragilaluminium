import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto("http://localhost:8200/login", { waitUntil: "networkidle" })
await page.fill("#login-identifier", "qa.admin@example.com")
await page.fill("#login-password", "QaScreenshot2026!")
await page.click('button[type="submit"]')
await page.waitForURL(/\/admin/, { timeout: 15000 })
await page.goto("http://localhost:8200/admin/orders", { waitUntil: "networkidle" })
await page.locator('article a[href*="/admin/orders/"]').first().click()
await page.waitForLoadState("networkidle")
await page.waitForTimeout(500)
await page.screenshot({ path: "/tmp/admin-shots/order-show-light.png", fullPage: true })
await browser.close()
console.log("done")
